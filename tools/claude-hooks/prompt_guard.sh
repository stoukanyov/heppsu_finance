#!/bin/bash
# UserPromptSubmit: вкарва в контекста задължителната ПЪРВА стъпка, когато
# репликата на Ив е от тип, при който отговор по памет е бил грешен.
# Lessons learned Beagle Owner, 11.09.2026: I3 (форензика първо), I11
# (упътване за екран, който не съм виждал), I12 (твърдения без „проверено с“).
#
# stdout се добавя към контекста на модела; хукът никога не блокира.
set -u
P=$(cat | python3 -c 'import json,sys; print(json.load(sys.stdin).get("prompt",""))' 2>/dev/null) || exit 0
L=$(printf '%s' "$P" | tr '[:upper:]' '[:lower:]')
out=""

if printf '%s' "$L" | grep -Eq 'не виждам|не намирам|няма так|не съвпада|къде е|no such|не го намирам|не съществува'; then
  out+="[prompt_guard] Ив не намира нещо в интерфейс. НЕ давай следващо упътване по памет: поискай снимка на екрана или URL (една стъпка). За собственото приложение — grep в lib/l10n/app_bg.arb и lib/screens и цитирай файл:ред.\n"
fi
if printf '%s' "$L" | grep -Eq '^(готово|подадох|натиснах|качих|спрях|върнах|submit|пуснах|събмитнах)'; then
  out+="[prompt_guard] Ив казва, че е натиснал бутон в стор/конзола. Преди да отговориш: провери състоянието през API (ASC reviewSubmissions + items; Play tracks) и цитирай изхода. „Готово“ на 10.09.2026 беше подаване с 1 елемент от 3.\n"
fi
if printf '%s' "$L" | grep -Eq 'не работи|дефект|грешка|пак същото|отново същ|странно|отхвърл|crash|краш'; then
  out+="[prompt_guard] Доклад за проблем. Първата стъпка е доказателство от ЖИВАТА система (edge/api лог, база, API на стора) с цитирана команда и ред; хипотези и статични агенти — след него (06.09.2026: 2 мин лог срещу 1,5 ч анализ).\n"
fi
if printf '%s' "$L" | grep -Eq 'продукци|production|деплойн|лайв|кой билд|коя версия|активни потребител'; then
  out+="[prompt_guard] Въпрос за живо състояние. Отговорът носи „проверено с: <команда/URL>, <час>“ — sha от /api/v1/health или от контейнера, версия/състояние от ASC/Play API, потребители по точни адреси, не от паметта.\n"
fi

[[ -n "$out" ]] && printf "$out"
exit 0
